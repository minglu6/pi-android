#!/usr/bin/env python3
"""gen-dep-r.py — 为每个依赖库生成它自己的 R 类（androidx.appcompat.R 等）。

背景（本机手搓 APK 最隐蔽的一个坑）：
    AAR 的 classes.jar 里引用的不是我们的 dev.pi.android.R，而是 androidx.appcompat.R、
    com.google.android.material.R —— 而 AAR 并不自带 R 类。Gradle 会按最终合并出的资源表
    为每个依赖包生成一份；我们没有 gradle，所以要自己补这一步。少了它，运行时的表现是
    `ClassNotFoundException: androidx.appcompat.R$drawable`，而且看不出来和资源合并有关。

做法：
    1. 读 libs/packages.json 拿到每个 AAR 的包名；
    2. 读该 AAR 的 R.txt 拿到它声明的资源名（type + name，忽略里面带的旧 id）；
    3. 读 aapt2 link 为应用生成的 R.java（资源全并进应用包了），按名字取最终 id；
    4. 在 build/gen/<包路径>/R.java 里写出 <pkg>.R，字段值取自应用的合并表 —— 二者一致，
       因为最终的 resources.arsc 就是这个表。

用法:
    tools/gen-dep-r.py --app-r build/gen/<app pkg>/R.java --libs libs --out build/gen
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import zipfile
from collections import defaultdict

# styleable 在 R.java 里是 int[]（索引数组 + 逐项下标），都得认出来，
# 否则会给依赖生成缺一半的 R：Material3 的主题样式几乎全靠 styleable 数组。
FIELD = re.compile(r"public static final int ([A-Za-z_0-9]+)=([0-9A-Fa-fx]+);")
ARRAY = re.compile(r"public static final int\[\] ([A-Za-z_0-9]+)=\{(.*?)\};", re.DOTALL)
CLASS = re.compile(r"public static final class ([A-Za-z_0-9]+) \{")


def parse_app_r(path: pathlib.Path) -> dict[str, dict[str, str]]:
    """读 aapt2 生成的 R.java → {type: {name: "0x7f..." 或 "{0x..., }"}}"""
    text = path.read_text()
    table: dict[str, dict[str, str]] = defaultdict(dict)
    for typ, body in re.findall(r"public static final class ([A-Za-z_0-9]+) \{(.*?)\n  \}", text, re.DOTALL):
        for name, value in ARRAY.findall(body):
            table[typ][name] = "{" + value.strip() + "}"
        for name, value in FIELD.findall(body):
            table[typ][name] = value
    return table


def read_r_txt(path: pathlib.Path) -> list[tuple[str, str]]:
    """AAR 的 R.txt：'int drawable abc_x 0x7f...' → [(type, name)]"""
    out = []
    for line in path.read_text().splitlines():
        parts = line.split()
        if len(parts) >= 3 and parts[0] in ("int", "int[]"):
            out.append((parts[1], parts[2]))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--app-r", required=True)
    ap.add_argument("--libs", default="libs")
    ap.add_argument("--out", default="build/gen")
    args = ap.parse_args()

    app_r = pathlib.Path(args.app_r).expanduser()
    libs = pathlib.Path(args.libs).expanduser().resolve()
    out = pathlib.Path(args.out).expanduser()
    table = parse_app_r(app_r)

    packages = json.loads((libs / "packages.json").read_text()) if (libs / "packages.json").exists() else {}
    seen: set[str] = set()
    written = 0
    missing = 0

    for aar_key, pkg in sorted(packages.items()):
        # packages.json 的 key 可能是相对或绝对路径，逐个候选兜底
        aar = pathlib.Path(aar_key)
        aar = next((c for c in (aar, pathlib.Path.cwd() / aar, libs / aar,
                                libs.parent / aar) if c.exists()), aar)
        rtxt = aar.parent / "R.txt"
        if not rtxt.exists():
            continue
        entries: dict[str, list[tuple[str, str]]] = defaultdict(list)
        for typ, name in read_r_txt(rtxt):
            entries[typ].append((name, table.get(typ, {}).get(name)))

        body: list[str] = [
            "/* AUTO-GENERATED by tools/gen-dep-r.py — 不要手改。",
            " * 依赖 AAR 的 classes.jar 引用本包同名资源，ids 取自最终应用的合并资源表。",
            " */",
            f"package {pkg};",
            "",
            "public final class R {",
        ]
        used = 0
        missing_local = 0
        for typ, items in sorted(entries.items()):
            body.append(f"  public static final class {typ} {{")
            for name, value in items:
                if value is None:
                    missing_local += 1
                    continue
                decl = "int[]" if value.startswith("{") else "int"
                body.append(f"    public static final {decl} {name}={value};")
                used += 1
            body.append("  }")
        body.append("}")
        if used == 0:
            continue

        target_dir = out / pkg.replace(".", "/")
        target_dir.mkdir(parents=True, exist_ok=True)
        (target_dir / "R.java").write_text("\n".join(body) + "\n")
        written += 1
        missing += missing_local
        if pkg not in seen and missing_local:
            print(f"  · {pkg}: {missing_local} 个资源名在合并表里没有（已跳过这些字段）")
        seen.add(pkg)

    print(f"已为 {written} 个依赖包生成 R.java（缺失字段 {missing} 个）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
